// Слова, пригодные для автогенерации (короткие), по slugs тем
export function eligibleWords(slugs) {
  const set = new Set(Array.isArray(slugs) ? slugs : [slugs]);
  const out = [];
  for (const t of THEMES) {
    if (!set.has(t.slug)) continue;
    for (let i = 0; i < t.words.length; i++) {
      const w = t.words[i];
      if (w.answer.length <= MAX_WORD_LEN_FOR_GRID) out.push({ answer: w.answer, clue: w.clue, clueId: t.slug + ':' + i, theme: t.slug });
    }
  }
  return out;
}

// Публичные метаданные тем: названия и количество слов, без вопросов и ответов
export function publicThemes() {
  return THEMES.map(t => ({
    slug: t.slug,
    code: t.code,
    name: t.name,
    description: t.description,
    totalCount: t.words.length,
    eligibleCount: t.words.filter(w => w.answer.length <= MAX_WORD_LEN_FOR_GRID).length
  }));
}

// Разбор clueId ("pb:3") -> {answer, clue} | null. Для конструктора преподавателя:
// слова по clueId подставляются на сервере, клиент их не видит.
export function byClueId(clueId) {
  if (typeof clueId !== 'string') return null;
  const m = /^(pb|pmla|asf|vpb|suot):(\d+)$/.exec(clueId);
  if (!m) return null;
  const t = THEMES.find(x => x.slug === m[1]);
  if (!t) return null;
  const w = t.words[Number(m[2])];
  return w ? { answer: w.answer, clue: w.clue, theme: t.slug } : null;
}

// Все пары clueId+вопрос темы (слова НЕ отдаём) — для панели преподавателя
export function cluesOfTheme(slug) {
  const t = THEMES.find(x => x.slug === slug);
  if (!t) return null;
  return {
    slug: t.slug,
    code: t.code,
    name: t.name,
    clues: t.words.map((w, i) => ({ clueId: t.slug + ':' + i, clue: w.clue, len: w.answer.length }))
  };
}
